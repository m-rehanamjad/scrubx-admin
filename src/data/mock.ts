const colorCode = (color: ProductColor) => color.name.split(" ")[0].slice(0, 3).toUpperCase();

function buildVariants(spec: ProductSpec): ProductVariant[] {
  const variants: ProductVariant[] = [];
  let index = 0;
  for (const color of spec.colors.map((id) => C(id))) {
    for (const size of spec.sizes) {
      const stock = spec.stock[index % spec.stock.length];
      variants.push({
        id: `${spec.id}-${color.id}-${sizeCode(size)}`,
        colorId: color.id,
        colorName: color.name,
        colorHex: color.hex,
        size,
        name: `${color.name} / ${size}`,
        sku: `${spec.skuPrefix}-${colorCode(color)}-${sizeCode(size)}`,
        price: spec.price,
        compareAtPrice: spec.compareAtPrice ?? null,
        stock,
        reserved: Math.min(stock, Math.round(stock * 0.08)),
        reorderLevel: 10,
        active: true,
      });
      index += 1;
    }
  }
  return variants;
}

